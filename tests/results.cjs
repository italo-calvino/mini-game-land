const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync('dist/client/index.html','utf8');
const claim=html.match(/function claimTerminalResult\([^]*?\n}/)[0];
const ctx={DIRECT_POINT_GAMES:new Set(['blackjack','roulette','slot','pachinko']),resultSession:null};
vm.createContext(ctx);vm.runInContext(claim,ctx);
ctx.resultSession={gameId:'quiz',finished:false};
assert.equal(ctx.claimTerminalResult('quiz',true),true);
assert.equal(ctx.claimTerminalResult('quiz',true),false,'a terminal result is only accepted once');
assert.equal(ctx.claimTerminalResult('memory',true),false,'stale callbacks from another game are ignored');
ctx.resultSession={gameId:'slot',finished:false};
assert.equal(ctx.claimTerminalResult('slot',true),true);
assert.equal(ctx.claimTerminalResult('slot',false),true,'casino rounds remain repeatable');
ctx.resultSession={gameId:'monster',finished:false};
assert.equal(ctx.claimTerminalResult('monster',true),true);
assert.equal(ctx.claimTerminalResult('monster',true),true,'monster victories continue the run');
assert.equal(ctx.claimTerminalResult('monster',false),true);
assert.equal(ctx.claimTerminalResult('monster',false),false,'monster defeat ends only once');
assert.match(html,/className='result-overlay'/);
assert.match(html,/aria-labelledby','unified-result-title'/);
assert.match(html,/onclick="startGame\('\$\{gameId\}'\)">もう一度/);
assert.match(html,/onclick="continueCasinoGame\('\$\{gameId\}'\)">もう一度/);
assert.match(html,/onclick="finishCasinoSession\('\$\{gameId\}'\)">終了/);
assert.match(html,/presentGameResult\(gameId,saveData\.totalScore-session\.initialWallet[^;]+true\)/);
assert.match(html,/roundDiff=result==='win'\?bet:result==='lose'\?-bet:0/);
assert.doesNotMatch(html,/>次のゲーム<\/button>/);
assert.doesNotMatch(html,/dismissGameResult\(\)">続ける/);
assert.match(html,/nativeResult\.appendChild\(box\)/);
assert.match(html,/setUnifiedResultMode\(true\);document\.body\.appendChild\(overlay\)/);
assert.match(html,/screen\.setAttribute\('inert',''\);screen\.setAttribute\('aria-hidden','true'\)/);
assert.match(html,/startGame\(name\) \{[^]*?setUnifiedResultMode\(false\)/);
console.log('PASS: unified result overlay, casino round retry/end flow, stale and duplicate result protection');
